/**
 * Expo config plugin: fix + rebrand the Android screen-share (MediaProjection)
 * foreground-service notification shown by `@livekit/react-native-webrtc`.
 *
 * Why this exists (RC-4): the library builds its media-projection FGS notification
 * with
 *   setSmallIcon(getResources().getIdentifier("ic_notification", "drawable", pkg))
 * and its strings come from R.string.media_projection_notification_{title,text} and
 * R.string.ongoing_notification_channel_name. Our app has NO `ic_notification`
 * drawable — expo-notifications generates `notification_icon` instead — so the lookup
 * returns 0, `setSmallIcon(0)` yields a BROKEN notification and Android falls back to a
 * generic "<app> is running…" system notice (confirmed in logcat:
 * "Attempted to start a foreground service … with a broken notification (no icon)").
 *
 * The fix needs NO native patch — just app-tier Android resources, which override the
 * library's AAR resources during the resource merge:
 *   1. A drawable ALIAS `ic_notification` -> `@drawable/notification_icon` so the
 *      library's by-name lookup resolves to our real (correctly white-tinted,
 *      density-bucketed) notification icon.
 *   2. Branded strings (EN default + TR) for the title/text/channel name.
 *
 * Written via a dangerous-mod after the Android project is generated, so it survives
 * `expo prebuild --clean`. Idempotent — re-running overwrites the same files.
 */
const { withDangerousMod } = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

const RES_FILE = "demli_media_projection.xml";

// Default (English). Also carries the drawable alias — value resources are not
// density/locale specific, so the alias lives here once and resolves everywhere.
const DEFAULT_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-media-projection-notification.js — do not edit. -->
<resources>
    <!--
      @livekit/react-native-webrtc resolves its media-projection notification icon by
      NAME (getIdentifier("ic_notification","drawable",pkg)). Our icon is generated by
      expo-notifications as notification_icon, so this alias points ic_notification at
      the real icon and keeps the small icon from resolving to 0 (a broken notification).
    -->
    <item name="ic_notification" type="drawable">@drawable/notification_icon</item>

    <!-- Rebrand the library's default (English) media-projection strings. -->
    <string name="media_projection_notification_title">Demli</string>
    <string name="media_projection_notification_text">You are sharing your screen</string>
    <string name="ongoing_notification_channel_name">Screen sharing</string>
</resources>
`;

// Turkish overrides (values-tr). Strings only — the drawable alias in values/ applies.
const TR_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-media-projection-notification.js — do not edit. -->
<resources>
    <string name="media_projection_notification_title">Demli</string>
    <string name="media_projection_notification_text">Ekranını paylaşıyorsun</string>
    <string name="ongoing_notification_channel_name">Ekran paylaşımı</string>
</resources>
`;

/**
 * @param {string} valuesDir absolute path to a res values(-qualifier) directory
 * @param {string} contents XML file contents
 */
function writeResourceFile(valuesDir, contents) {
  fs.mkdirSync(valuesDir, { recursive: true });
  fs.writeFileSync(path.join(valuesDir, RES_FILE), contents, "utf8");
}

module.exports = function withMediaProjectionNotification(config) {
  return withDangerousMod(config, [
    "android",
    (cfg) => {
      const resPath = path.join(
        cfg.modRequest.platformProjectRoot,
        "app",
        "src",
        "main",
        "res",
      );
      writeResourceFile(path.join(resPath, "values"), DEFAULT_XML);
      writeResourceFile(path.join(resPath, "values-tr"), TR_XML);
      return cfg;
    },
  ]);
};
