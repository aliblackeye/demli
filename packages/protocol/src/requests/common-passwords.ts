/** Lowercased common passwords, O(1) membership. */
const COMMON_PASSWORDS: ReadonlySet<string> = new Set(
  COMMON_PASSWORD_LIST.split("\n").filter((line) => line.length > 0),
);

/** Number of entries in the denylist. Exported so a test can assert it never silently shrinks. */
export const COMMON_PASSWORD_COUNT = COMMON_PASSWORDS.size;

/**
 * True when `password` is on the common-password denylist.
 *
 * Case-insensitive by design (see the file header). Callers pass the RAW password —
 * this function does the lowercasing, so no caller can forget it and quietly let
 * `PASSWORD123` through.
 */
export function isCommonPassword(password: string): boolean {
  return COMMON_PASSWORDS.has(password.toLowerCase());
}
