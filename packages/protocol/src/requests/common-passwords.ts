/**
 * The embedded common-password denylist (1000 entries).
 *
 * Rejecting a *known-breached* password is the one password rule NIST SP 800-63B
 * actually asks for (§5.1.1.2 "compare against a list of commonly-used, expected,
 * or compromised values"). It is also the one that buys real security: the
 * classic "1 uppercase + 1 digit + 1 symbol" composition rules push people to
 * `Password1!` — which is IN this list — while a long passphrase they can
 * remember is not. So Demli enforces length (8..128) plus this list, and no
 * composition rules at all (see `requests/auth.ts`).
 *
 * Source: SecLists (MIT) — `Passwords/Common-Credentials/10k-most-common.txt`,
 * https://github.com/danielmiessler/SecLists — the RockYou-derived frequency-ranked
 * list. Filtered to entries of length >= 8 (shorter ones can never reach the
 * password field: the min-length rule rejects them first, so carrying them would
 * be dead weight) and truncated to the top 1000 by rank. Entries are
 * lowercased and compared case-insensitively, because `Password123` is exactly as
 * guessable as `password123` — an attacker's list is case-permuted anyway.
 *
 * Deliberately a plain embedded list and NOT a dependency: this ships inside the
 * browser/RN bundle so the sign-up form can reject locally with a real message,
 * and a ~9 KB string (~4 KB gzipped) is cheaper than any package that would pull
 * in a wordlist plus an entropy estimator. It is intentionally NOT exhaustive —
 * it is a "stop the top of the distribution" guard, not a breach-corpus check.
 *
 * Regenerate: download the source list, keep length >= 8, dedupe case-insensitively,
 * take the first 1000 by rank.
 */

